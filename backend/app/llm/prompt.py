"""Построение системного промпта и схемы ответа для LLM-анализа."""
from __future__ import annotations

from typing import List

from ..knowledge.loader import get_knowledge

SYSTEM_PROMPT = """\
Ты — эксперт по законодательству Российской Федерации о рекламе (прежде всего \
Федеральный закон № 38-ФЗ «О рекламе»), а также по смежным нормам: КоАП РФ \
(ст. 14.3), ФЗ-152 «О персональных данных», ФЗ-436 «О защите детей от информации», \
Закон «О защите прав потребителей».

Твоя задача — проверить рекламную коммуникацию на правовые риски и вернуть строго \
JSON-массив находок. Анализируй СМЫСЛ и КОНТЕКСТ (детерминированные проверки по \
стоп-словам уже выполнены отдельно — ищи то, что можно понять только из смысла: \
скрытые обещания, вводящие в заблуждение утверждения, неуместные образы, \
подразумеваемые сравнения, риски конкретной товарной категории и т.п.).

Правила вывода:
- Возвращай ТОЛЬКО валидный JSON-массив, без markdown-обёртки и пояснений.
- Не выдумывай номера статей и штрафы. Если не уверен в точной норме — указывай \
общую статью (например «ст. 5 ФЗ-38») и отметь неуверенность в поле confidence.
- Не дублируй очевидные формальные проверки (наличие erid, пометки «реклама», \
возрастной маркировки) — они уже проверены движком правил.
- Если реальных рисков нет — верни пустой массив [].
- Каждый риск должен быть обоснованным и практически значимым.

Формат каждого элемента массива:
{
  "title": "краткое название риска",
  "description": "в чём риск и почему (со ссылкой на смысл рекламы)",
  "evidence": "цитата или фрагмент рекламы, вызывающий риск (или null)",
  "risk_level": "low | medium | high | critical",
  "legal_basis": [{"law": "...", "article": "ст. X ч. Y", "title": "...", "summary": "..."}],
  "mitigation": ["как снизить риск — конкретные шаги"],
  "liability": {"koap_article": "ст. 14.3 ...", "fine_legal": "диапазон для юрлиц или null"},
  "confidence": 0.0-1.0
}
"""


def build_user_prompt(text: str, categories: List[str]) -> str:
    kb = get_knowledge()
    cat_lines = []
    for cat_key in categories:
        cat = kb.categories.get(cat_key, {})
        title = cat.get("title", cat_key)
        prohibitions = "; ".join(cat.get("prohibitions", []))
        cat_lines.append(f"- {title}: {prohibitions}" if prohibitions else f"- {title}")

    cat_block = (
        "Предварительно определённые товарные категории (учитывай их особый режим):\n"
        + "\n".join(cat_lines)
        if cat_lines
        else "Товарные категории с особым режимом предварительно не выявлены."
    )

    return (
        f"{cat_block}\n\n"
        f"=== ТЕКСТ РЕКЛАМНОЙ КОММУНИКАЦИИ ===\n{text}\n=== КОНЕЦ ТЕКСТА ===\n\n"
        "Верни JSON-массив смысловых правовых рисков по инструкции."
    )
