export type PromotionReadinessItem = {
  id: 'qualification' | 'identity' | 'timeline' | 'mechanics' | 'prizes'
  label: string
  ready: boolean
  detail: string
  critical?: boolean
}

export function getPromotionReadiness(draft: PromotionDraft): PromotionReadinessItem[] {
  const datesInOrder = Boolean(draft.startDate && draft.endDate && draft.startDate <= draft.endDate)
  const entriesInRange = Boolean(draft.entryStartDate && draft.entryEndDate && draft.entryStartDate <= draft.entryEndDate && (!draft.startDate || draft.entryStartDate >= draft.startDate) && (!draft.endDate || draft.entryEndDate <= draft.endDate))
  const criticalLotteryRisk = draft.separateParticipationFee && draft.randomSelection

  return [
    { id: 'qualification', label: 'Квалификация', ready: !criticalLotteryRisk, critical: criticalLotteryRisk, detail: criticalLotteryRisk ? 'Платное участие + случайный выигрыш: критический риск лотереи' : 'Тип акции и способ определения результата согласованы' },
    { id: 'identity', label: 'Организатор', ready: Boolean(draft.organizer.trim() && draft.organizerDetails.trim() && draft.rulesUrl.trim()), detail: 'Нужны наименование, реквизиты и адрес полных правил' },
    { id: 'timeline', label: 'Сроки', ready: Boolean(datesInOrder && entriesInRange && draft.winnerDate && draft.deliveryEndDate), detail: 'Общий период, заявки, выбор победителей и выдача призов' },
    { id: 'mechanics', label: 'Механика', ready: Boolean(draft.mechanics.trim() && draft.entryLimit.trim() && draft.rejectionGrounds.trim()), detail: 'Действия, лимиты, проверка и основания отклонения' },
    { id: 'prizes', label: 'Призы', ready: Boolean(draft.prizes.trim() && draft.winnerMethod.trim() && draft.notificationMethod.trim() && draft.unclaimedPrizes.trim()), detail: 'Состав, выбор, уведомление, выдача и невостребованные призы' },
  ]
}

function formatRuleDate(value: string): string {
  if (!value) return '«указать дату»'
  return new Date(`${value}T00:00:00`).toLocaleDateString('ru-RU')
}

