function formatRuleDate(value: string): string {
  if (!value) return '«указать дату»'
  return new Date(`${value}T00:00:00`).toLocaleDateString('ru-RU')
}

export function generatePromotionRules(draft: PromotionDraft): string {
  const start = formatRuleDate(draft.startDate)
  const end = formatRuleDate(draft.endDate)
  const participationFee = draft.purchaseRequired
    ? 'Отдельная плата за участие не взимается. Стоимость приобретаемого товара не увеличивается в связи с проведением Акции.'
    : 'Участие является бесплатным. Внесение платы и приобретение товара для участия не требуются.'
  const winnerSelection = draft.randomSelection
    ? `Определение победителей проводится случайным способом: ${draft.winnerMethod || '«указать используемый способ и порядок фиксации результатов»'}. Организатор оформляет протокол с результатами.`
    : `Победители определяются по заранее установленным критериям: ${draft.winnerMethod || '«указать критерии, состав жюри и порядок оценки»'}. Результаты оформляются протоколом.`
  const personalData = draft.collectsPersonalData
    ? `Для участия обрабатываются персональные данные, необходимые для регистрации, связи с участником, определения победителей и вручения призов. Оператором персональных данных является ${draft.organizer || '«указать организатора»'}. Обработка осуществляется на основании отдельного согласия участника в течение срока, необходимого для проведения Акции и исполнения обязанностей Организатора. Участник вправе отозвать согласие способом, указанным в политике обработки персональных данных.${draft.publishesWinners ? ' Публикация ФИО, изображения или иных данных победителя осуществляется только при наличии отдельного согласия на распространение персональных данных.' : ''}`
    : 'Организатор не собирает персональные данные сверх сведений, получение которых необходимо для исполнения обязанностей по передаче приза. При необходимости обработки таких сведений Организатор получает надлежащее согласие участника.'

  return `ПРАВИЛА ПРОВЕДЕНИЯ ${PROMOTION_KIND_LABEL[draft.kind].toUpperCase()}
«${draft.name || 'НАЗВАНИЕ АКЦИИ'}»

1. ОБЩИЕ ПОЛОЖЕНИЯ
1.1. Настоящие Правила определяют порядок организации и проведения мероприятия «${draft.name || 'Название акции'}» (далее — «Акция»).
1.2. Вид мероприятия: ${PROMOTION_KIND_LABEL[draft.kind]}.
1.3. Акция проводится за счёт средств Организатора, не является государственной лотереей и не связана с внесением участниками отдельной платы за право участия.
1.4. ${participationFee}

2. ОРГАНИЗАТОР
2.1. Организатор: ${draft.organizer || '«указать полное наименование»'}.
2.2. Реквизиты Организатора: ${draft.organizerDetails || '«указать адрес, ИНН, ОГРН и контактные данные»'}.
2.3. Информация об Акции и актуальная редакция Правил размещаются по адресу: ${draft.rulesUrl || '«указать адрес страницы с Правилами»'}.

3. ТЕРРИТОРИЯ И СРОКИ
3.1. Территория проведения: ${draft.territory || '«указать территорию»'}.
3.2. Общий срок проведения Акции: с ${start} по ${end} включительно.
3.3. Период приёма заявок совпадает с общим сроком проведения Акции, если иное прямо не указано Организатором до начала приёма заявок.

4. УЧАСТНИКИ
4.1. Участниками могут быть: ${draft.participants || '«указать требования к участникам»'}.
4.2. Работники Организатора и лица, непосредственно участвующие в организации Акции, не допускаются к участию, если иное прямо не предусмотрено настоящими Правилами.
4.3. Участник обязан предоставлять достоверные сведения и соблюдать настоящие Правила.

5. ПОРЯДОК УЧАСТИЯ
5.1. Для участия необходимо: ${draft.mechanics || '«подробно описать последовательность действий участника»'}.
5.2. Одна заявка должна соответствовать всем требованиям настоящих Правил. Основания отклонения заявки применяются одинаково ко всем участникам.
5.3. Организатор обеспечивает возможность подтвердить факт и время регистрации заявки.

6. ПРИЗОВОЙ ФОНД
6.1. Призовой фонд: ${draft.prizes || '«указать наименование, количество и стоимость каждого вида призов»'}.
6.2. Призы формируются за счёт средств Организатора. Денежный эквивалент и замена приза не предоставляются, если иное не установлено Организатором.

7. ОПРЕДЕЛЕНИЕ ПОБЕДИТЕЛЕЙ
7.1. ${winnerSelection}
7.2. Результаты не могут изменяться после оформления протокола, кроме исправления очевидной технической ошибки с документальным обоснованием.
7.3. Информация о победителях доводится до участников способом, указанным в пункте 2.3 настоящих Правил.

8. ПОРЯДОК ПОЛУЧЕНИЯ ПРИЗОВ
8.1. ${draft.prizeDelivery || '«указать срок, место и порядок получения призов»'}.
8.2. Победитель предоставляет только сведения и документы, объективно необходимые для идентификации, передачи приза и исполнения налоговых обязанностей.
8.3. Если победитель не отвечает или не предоставляет необходимые сведения, Организатор направляет повторное уведомление и предоставляет разумный дополнительный срок. После его истечения приз может быть признан невостребованным.

9. ПЕРСОНАЛЬНЫЕ ДАННЫЕ
9.1. ${personalData}
9.2. Согласие на участие в Акции не является согласием на получение рекламных рассылок. Такое согласие запрашивается отдельно.

10. НАЛОГООБЛОЖЕНИЕ
10.1. Налогообложение призов осуществляется в соответствии с законодательством Российской Федерации. Организатор сообщает победителю стоимость приза и порядок исполнения применимых налоговых обязанностей.
10.2. При невозможности удержать налог Организатор выполняет предусмотренные законом обязанности по уведомлению налогового органа и победителя.

11. ИНФОРМИРОВАНИЕ И ИЗМЕНЕНИЕ ПРАВИЛ
11.1. Актуальная редакция Правил размещается по адресу, указанному в пункте 2.3.
11.2. Изменения не должны ухудшать положение уже зарегистрированных участников, произвольно менять критерии выбора победителей или состав объявленного призового фонда. Информация об изменениях публикуется тем же способом, что и настоящие Правила.
11.3. Реклама Акции должна содержать сроки её проведения и источник информации об Организаторе, Правилах, количестве призов, сроках, месте и порядке их получения.

12. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ
12.1. Споры разрешаются путём переговоров, а при недостижении соглашения — в порядке, установленном законодательством Российской Федерации.
12.2. Организатор отвечает за исполнение принятых обязательств в пределах, установленных законом и настоящими Правилами.

Проект требует проверки с учётом фактической механики, рекламных материалов, формы согласия на обработку персональных данных, применяемых сервисов и характеристик призов.`
}

function basis(law: string, article: string, title: string, summary: string) {
  return [{ law, article, title, summary }]
}

function createFinding(id: string, title: string, description: string, riskLevel: RiskLevel, law: string, article: string, legalTitle: string, legalSummary: string, mitigation: string[], evidence?: string): Finding {
  return {
    id,
    category: 'promotion_rules',
    title,
    description,
    evidence,
    risk_level: riskLevel,
    legal_basis: basis(law, article, legalTitle, legalSummary),
    mitigation,
    practice: [],
    source: 'rule',
    confidence: 0.9,
  }
}

export function buildPromotionRulesReport(text: string, baseReport: Report): Report {
  const normalized = text.toLowerCase()
  const findings = baseReport.findings.filter((finding) => finding.id !== 'promo_event')
  const dates = text.match(/\b\d{1,2}[./-]\d{1,2}[./-]\d{4}\b/g) ?? []

  if (!/организатор/.test(normalized) || !/(инн|огрн|огрнип)/.test(normalized)) {
    findings.push(createFinding('promotion-organizer', 'Недостаточно сведений об организаторе', 'В правилах не обнаружены одновременно полное указание организатора и его идентифицирующие реквизиты.', 'high', 'ФЗ № 38-ФЗ «О рекламе»', 'ст. 9', 'Сведения о стимулирующем мероприятии', 'Реклама мероприятия должна вести к источнику информации об организаторе и правилах.', ['Укажите полное наименование, адрес, ИНН, ОГРН/ОГРНИП и рабочие контакты организатора.']))
  }
  if (dates.length < 2 && !/(срок проведения|период проведения)[\s\S]{0,120}(с|до|по)/.test(normalized)) {
    findings.push(createFinding('promotion-dates', 'Не определены полные сроки акции', 'Нельзя однозначно установить дату начала и дату окончания мероприятия или период приёма заявок.', 'high', 'ФЗ № 38-ФЗ «О рекламе»', 'ст. 9', 'Сроки стимулирующего мероприятия', 'В рекламе стимулирующего мероприятия должны быть указаны сроки его проведения.', ['Укажите даты начала и окончания, период регистрации заявок, дату выбора победителей и срок вручения призов.']))
  }
  if (!/территори/.test(normalized)) {
    findings.push(createFinding('promotion-territory', 'Не указана территория проведения', 'Участник не может определить, где действует акция и имеются ли территориальные ограничения.', 'medium', 'Закон РФ № 2300-1 «О защите прав потребителей»', 'ст. 10', 'Информация об условиях предложения', 'Существенные условия предложения должны быть понятны потребителю.', ['Добавьте отдельный пункт с территорией проведения и объективными ограничениями.']))
  }
  if (!/(требовани.{0,30}участник|участниками могут|возраст|18 лет|совершеннолет)/.test(normalized)) {
    findings.push(createFinding('promotion-participants', 'Нет требований к участникам', 'Не определены возраст, дееспособность, место проживания и исключения из состава участников.', 'medium', 'Гражданский кодекс РФ', 'ст. 26, 28', 'Участие несовершеннолетних', 'Возраст и дееспособность могут влиять на возможность совершать юридически значимые действия.', ['Опишите требования к участникам и отдельно урегулируйте участие несовершеннолетних.']))
  }
  if (!/(порядок участия|для участия|участник должен|механик)/.test(normalized)) {
    findings.push(createFinding('promotion-mechanics', 'Механика участия сформулирована неполно', 'Не обнаружена последовательность действий, необходимая для регистрации участия.', 'high', 'Гражданский кодекс РФ', 'ст. 1055–1061', 'Публичное обещание награды и конкурс', 'Условия получения награды и порядок выполнения задания должны быть определимыми.', ['Опишите действия участника по шагам, сроки, ограничения количества заявок и основания отклонения.']))
  }
  if (!/(призов(ой|ый) фонд|количеств.{0,30}приз|наименование.{0,30}приз)/.test(normalized)) {
    findings.push(createFinding('promotion-prizes', 'Не раскрыт призовой фонд', 'Не определены наименование и количество призов, а также их основные характеристики.', 'high', 'ФЗ № 38-ФЗ «О рекламе»', 'ст. 9', 'Информация о призах', 'Источник правил должен раскрывать количество призов и порядок их получения.', ['Перечислите каждый вид приза, количество, стоимость и допустимость замены.']))
  }
  if (!/(определени.{0,40}победител|победител.{0,40}определ|критери.{0,30}оцен|случайн.{0,30}(выбор|способ)|жюри)/.test(normalized)) {
    findings.push(createFinding('promotion-winners', 'Неясно, как определяются победители', 'Правила не позволяют проверить метод выбора победителей и фиксацию результатов.', 'high', 'Гражданский кодекс РФ', 'ст. 1057–1061', 'Условия публичного конкурса', 'Порядок оценки и определения результата должен быть заранее понятен участникам.', ['Укажите метод выбора, дату, критерии или алгоритм, состав комиссии и форму протокола.']))
  }
  if (!/(получени.{0,40}приз|вручен.{0,40}приз|передач.{0,40}приз|доставк.{0,40}приз)/.test(normalized)) {
    findings.push(createFinding('promotion-delivery', 'Нет порядка получения призов', 'Не определены сроки, место, способ вручения и последствия неполучения приза.', 'high', 'ФЗ № 38-ФЗ «О рекламе»', 'ст. 9', 'Получение призов', 'Источник правил должен содержать сроки, место и порядок получения призов.', ['Опишите уведомление победителя, документы, срок передачи и порядок работы с невостребованным призом.']))
  }
  if (!/персональн.{0,20}данн/.test(normalized)) {
    findings.push(createFinding('promotion-personal-data', 'Не урегулирована обработка персональных данных', 'Для регистрации участников и вручения призов обычно обрабатываются идентификаторы и контакты, но соответствующего раздела нет.', 'high', 'ФЗ № 152-ФЗ «О персональных данных»', 'ст. 5, 6, 9, 10.1', 'Обработка персональных данных участников', 'Обработка должна иметь правовое основание, конкретные цели и надлежащую форму согласия.', ['Укажите оператора, цели, состав данных, действия, срок хранения и отзыв согласия.', 'Получайте отдельные согласия на рекламную рассылку и на распространение данных победителя.']))
  }
  if (!/(налог|ндфл|налогооблож)/.test(normalized)) {
    findings.push(createFinding('promotion-taxes', 'Не описаны налоговые последствия призов', 'Победитель не предупреждён о применимом налогообложении и порядке исполнения обязанностей.', 'medium', 'Налоговый кодекс РФ', 'ст. 217, 224, 226', 'Налогообложение выигрышей и призов', 'Для призов в рекламных мероприятиях действует специальный порядок налогообложения.', ['Добавьте пункт о стоимости приза, обязанностях налогового агента и информировании победителя.']))
  }

  const unilateral = text.match(/организатор[^.]{0,120}(вправе|может)[^.]{0,70}измен[^.]{0,70}(любое время|односторон)/i)?.[0]
  if (unilateral) {
    findings.push(createFinding('promotion-unilateral-change', 'Неограниченное право менять правила', 'Оговорка позволяет организатору произвольно изменить существенные условия после начала акции.', 'high', 'Гражданский кодекс РФ', 'ст. 1058', 'Изменение условий публичного конкурса', 'Для публичного конкурса изменение или отмена условий ограничены законом.', ['Ограничьте основания и срок изменений, сохраните права зарегистрированных участников и публикуйте изменения тем же способом.'], unilateral))
  }
  const jurisdiction = text.match(/(только|исключительно)[^.]{0,100}(суд|месту нахождения организатора)/i)?.[0]
  if (jurisdiction) {
    findings.push(createFinding('promotion-jurisdiction', 'Ограничена подсудность участника', 'Условие может лишать потребителя предусмотренного законом выбора суда.', 'medium', 'Закон РФ № 2300-1 «О защите прав потребителей»', 'ст. 16, 17', 'Недопустимые условия и судебная защита', 'Условия, ущемляющие права потребителя по сравнению с законом, не применяются.', ['Замените условие на: «Споры разрешаются в порядке, установленном законодательством Российской Федерации».'], jurisdiction))
  }
  const paidParticipation = /(плата за участие|участие является платным|вступительн.{0,20}взнос)/.test(normalized)
  const randomSelection = /(случайн|рандом|генератор.{0,20}случайн)/.test(normalized)
  if (paidParticipation && randomSelection) {
    findings.push(createFinding('promotion-lottery', 'Признаки незаконной лотереи', 'Одновременно обнаружены отдельная плата за участие и случайный способ определения выигрыша.', 'critical', 'ФЗ № 138-ФЗ «О лотереях»', 'ст. 6', 'Ограничения на проведение лотерей', 'Проведение лотерей допускается только в предусмотренном законом порядке.', ['Уберите отдельную плату или полностью переработайте механику с учётом требований законодательства о лотереях.']))
  }
  const ugc = /(фото|видео|творческ.{0,20}работ|рисунок|произведени)/.test(normalized)
  if (ugc && !/(лицензи|авторск.{0,20}прав|исключительн.{0,20}прав)/.test(normalized)) {
    findings.push(createFinding('promotion-ugc-rights', 'Не урегулированы права на конкурсные материалы', 'Акция предполагает пользовательский контент, но правила не определяют объём и срок его использования организатором.', 'medium', 'Гражданский кодекс РФ', 'ст. 1234–1236', 'Распоряжение исключительными правами', 'Передача права или лицензия требуют определённых законом условий.', ['Опишите неисключительную лицензию: способы использования, территорию, срок и указание автора.']))
  }

  const riskWeight: Record<RiskLevel, number> = { low: 1, medium: 2, high: 3, critical: 4 }
  const overallRisk = findings.reduce<RiskLevel>((highest, finding) => riskWeight[finding.risk_level] > riskWeight[highest] ? finding.risk_level : highest, 'low')

  return {
    ...baseReport,
    overall_risk: overallRisk,
    summary: findings.length === 0
      ? 'Явных формальных рисков в тексте правил не обнаружено. До запуска необходимо сопоставить правила с рекламными материалами, формами согласий и фактической механикой.'
      : `В правилах обнаружено ${findings.length} замечаний. Исправьте критичные и высокие риски до запуска акции и передайте финальную редакцию юристу.`,
    detected_categories: Array.from(new Set([...baseReport.detected_categories, 'promotion'])),
    findings,
    extracted_text: text,
    disclaimer: 'Данный анализ носит информационный характер и не является юридической консультацией. Перед запуском акции рекомендуется проверка у практикующего юриста.',
    meta: {
      ...baseReport.meta,
      rules_findings: findings.filter((finding) => finding.source === 'rule').length,
      warnings: Array.from(new Set([...baseReport.meta.warnings, 'Отдельно проверьте рекламные креативы акции: сроки и источник полных правил по статье 9 ФЗ № 38-ФЗ.', 'Формы согласий, техническая схема выбора победителя и свойства призов требуют отдельной проверки.'])),
      product_description: 'Правила маркетинговой акции, конкурса или розыгрыша',
    },
  }
}

export function downloadPromotionRulesAsWord(text: string, title: string): void {
  const escaped = text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const html = `<!doctype html><html><head><meta charset="utf-8"><style>body{font-family:Arial,sans-serif;font-size:11pt;line-height:1.5;color:#111}pre{font:inherit;white-space:pre-wrap}</style></head><body><pre>${escaped}</pre></body></html>`
  const blob = new Blob(['\ufeff', html], { type: 'application/msword;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = `${(title || 'Правила акции').replace(/[\\/:*?"<>|]+/g, '_')}.doc`
  document.body.appendChild(anchor)
  anchor.click()
  anchor.remove()
  window.setTimeout(() => URL.revokeObjectURL(url), 1_000)
}
